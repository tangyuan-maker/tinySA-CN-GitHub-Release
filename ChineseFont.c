const cn_glyph_t *cn_font_find(uint32_t codepoint) {
  int lo = 0;
  int hi = (int)(sizeof(glyphs) / sizeof(glyphs[0])) - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    if (glyphs[mid].codepoint == codepoint) return &glyphs[mid];
    if (glyphs[mid].codepoint < codepoint) lo = mid + 1;
    else hi = mid - 1;
  }
  return NULL;
}
